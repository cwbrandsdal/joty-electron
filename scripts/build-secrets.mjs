// Bundles the web app's secret detector (../joty-web/src/joty/engine/secrets.ts)
// into electron/generated/secrets.cjs for the main process, so the log writer
// and Copy diagnostics redact with exactly the detection the editor uses.
// The output is generated, gitignored and packaged with electron/**. Runs from
// `npm run build`, before `npm test`, `npm start`, `npm run dev` and the smoke test.
import { build } from "esbuild";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.resolve(root, "../joty-web/src/joty/engine/secrets.ts");
const outfile = path.join(root, "electron", "generated", "secrets.cjs");

if (!fs.existsSync(entry)) {
  console.error(
    `build-secrets: ${entry} is missing. The joty-web clone must sit next to joty-electron (see README).`,
  );
  process.exit(1);
}

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  format: "cjs",
  platform: "node",
  // Electron 43's Node; regex lookbehind and the `d` flag need nothing newer.
  target: "node20",
  legalComments: "none",
  logLevel: "warning",
  banner: {
    js: "// Generated by scripts/build-secrets.mjs from joty-web/src/joty/engine/secrets.ts. Do not edit.",
  },
});

// Fail the build when the bundle does not expose what electron/redact.cjs uses.
const detector = createRequire(import.meta.url)(outfile);
if (typeof detector.findSecrets !== "function") {
  console.error("build-secrets: the bundled detector has no findSecrets export.");
  process.exit(1);
}
console.log(`build-secrets: wrote ${path.relative(root, outfile)}`);
